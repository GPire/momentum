// A tiny search index generated from the existing verified SEC panel.
// Full filings remain lazy and are loaded only when someone opens a company.
import { writeFileSync } from 'node:fs';
import { AZIENDE_PANEL, SEC_PANEL_SCARICATO_IL } from '../src/alpha/panel-settoriale.js';

const entries = AZIENDE_PANEL.filter((row) => row.ticker && row.nome)
  .map((row) => [row.ticker, row.nome]);
const source = `// GENERATED by scripts/generate-sec-catalog.mjs from panel-settoriale.js. Do not edit.\n` +
  `export const SEC_CATALOG_SCARICATO_IL = ${JSON.stringify(SEC_PANEL_SCARICATO_IL)};\n` +
  `export const SEC_CATALOG_INDEX = ${JSON.stringify(entries)};\n`;
writeFileSync(new URL('../src/alpha/sec-catalog-index.js', import.meta.url), source);
